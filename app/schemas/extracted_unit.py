"""Schemas for extracted content units and extraction status.

Every field maps 1:1 to a column in the ``public.extracted_units`` table
(see ``database/migrations/003_extracted_units_integration.sql``).
"""

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

# The live extracted_units table enforces CHECK constraints on these columns
# (verified against the actual database); the API mirrors them so invalid
# values are rejected here with a 422 instead of failing in the database.
CONTENT_TYPES = ("text", "table", "transcript", "image", "diagram")
UNIT_STATUSES = ("extracted", "failed", "warning")


class ExtractedUnitCreate(BaseModel):
    """A unit of extracted content, as produced by an extraction engine.

    This is the shape extraction engines emit. ``id`` and the timestamps
    are generated by the database; ``metadata`` is a free-form JSON object
    that keeps extra provenance such as warnings, OCR flags or the original
    text source so no page/slide/asset metadata is discarded.
    """

    material_id: str
    content_type: Literal[*CONTENT_TYPES]
    content: str | None = Field(default=None, max_length=2_000_000)
    page_number: int | None = Field(default=None, ge=1)
    slide_number: int | None = Field(default=None, ge=1)
    start_timestamp_seconds: float | None = Field(default=None, ge=0)
    end_timestamp_seconds: float | None = Field(default=None, ge=0)
    asset_path: str | None = Field(default=None, max_length=500)
    extraction_method: str = Field(min_length=1, max_length=64)
    status: Literal[*UNIT_STATUSES] = "extracted"
    unit_order: int = 0
    metadata: dict[str, Any] = Field(default_factory=dict)


class ExtractedUnitResponse(BaseModel):
    """A row from the ``extracted_units`` table."""

    id: str
    material_id: str
    content_type: str
    content: str | None = None
    page_number: int | None = None
    slide_number: int | None = None
    start_timestamp_seconds: float | None = None
    end_timestamp_seconds: float | None = None
    asset_path: str | None = None
    extraction_method: str
    status: str = "extracted"
    unit_order: int = 0
    metadata: dict[str, Any] = Field(default_factory=dict)
    created_at: str | None = None
    updated_at: str | None = None


class ExtractedUnitUpdate(BaseModel):
    """The mutable parts of an extracted unit.

    Only the status, content and metadata are editable — the source location
    columns (page, slide, timestamps) identify where the content came from
    and are never rewritten after extraction, so any other field is rejected.
    """

    model_config = ConfigDict(extra="forbid")

    content: str | None = Field(default=None, max_length=2_000_000)
    status: Literal[*UNIT_STATUSES] | None = None
    metadata: dict[str, Any] | None = None


class ExtractionStatusResponse(BaseModel):
    """Processing status for one material.

    ``stage`` is the live extraction phase reported by the running background
    task (for example ``extracting_audio`` or ``transcribing`` for a video);
    it is ``None`` when nothing is running or the stage is unknown.
    """

    material_id: str
    status: str
    unit_count: int
    warnings: list[str] = Field(default_factory=list)
    stage: str | None = None
    updated_at: str | None = None