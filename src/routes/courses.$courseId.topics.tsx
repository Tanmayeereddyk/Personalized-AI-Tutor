import { createFileRoute, Link, useNavigate, useRouterState } from "@tanstack/react-router";
import {
  AlertCircle,
  ChevronDown,
  FileText,
  FolderOpen,
  Layers,
  Loader2,
  Network,
  RefreshCw,
  Sparkles,
} from "lucide-react";
import { toast } from "sonner";

import { ApiError } from "@/lib/api";
import {
  useGenerateTopics,
  useMaterials,
  useRefreshTopics,
  useTopics,
} from "@/lib/queries";
import type { Topic } from "@/lib/types";
import { cn } from "@/lib/utils";
import { EmptyState, PageHeader } from "@/components/ui/kit";

export const Route = createFileRoute("/courses/$courseId/topics")({
  component: Topics,
});

/** How many source documents are named before collapsing to "+N more". */
const MAX_SOURCE_CHIPS = 4;

/**
 * The course knowledge map.
 *
 * Topics are generated by the backend from the course's *indexed*
 * materials (the same RAG index that powers notes and the tutor).
 * This page never generates on its own: extraction already refreshes
 * the map in the background, so the Generate button is a manual,
 * explicit action and Refresh updates the map after new materials
 * land. The selected topic rides in the URL hash (e.g. #<topicId>)
 * so the open panel can be shared and survives a reload — the same
 * pattern the Materials page uses.
 */
export function Topics() {
  const { courseId } = Route.useParams();
  const topics = useTopics(courseId);
  const materials = useMaterials(courseId);
  const generate = useGenerateTopics(courseId);
  const refresh = useRefreshTopics(courseId);
  const navigate = useNavigate();

  const list = topics.data ?? [];

  // Topic rows carry material ids, not names, so resolve them against
  // the (already cached) course materials to name the sources.
  const materialNames = new Map(
    (materials.data ?? []).map((m) => [m.id, m.name] as const),
  );

  const requested = useRouterState({
    select: (s) => s.location.hash.replace(/^#/, ""),
  });
  const selected = requested ? list.find((t) => t.id === requested) : undefined;

  const selectTopic = (topic: Topic) => {
    void navigate({
      to: "/courses/$courseId/topics",
      params: { courseId },
      hash: selected?.id === topic.id ? "" : topic.id,
      replace: true,
    });
  };

  const busy = generate.isPending || refresh.isPending;

  const generateTopics = async () => {
    try {
      await generate.mutateAsync();
      toast.success("Topics generated from your materials.");
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : "Couldn't generate topics.",
      );
    }
  };

  const refreshTopics = async () => {
    try {
      await refresh.mutateAsync();
      toast.success("Topics refreshed from your materials.");
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : "Couldn't refresh topics.",
      );
    }
  };

  // A failed generate/refresh is shown inline as well as as a toast, so
  // the actionable backend messages (add materials, index first, LLM
  // not configured) stay visible next to the button that failed.
  const actionError = (generate.error ?? refresh.error) as Error | null;

  return (
    <div>
      <PageHeader
        title="Topics"
        subtitle="Your course knowledge map, generated from your own materials."
        action={
          <div className="flex flex-wrap items-center gap-2">
            {list.length > 0 ? (
              <button
                className="btn btn-primary"
                onClick={() => void refreshTopics()}
                disabled={busy}
              >
                {refresh.isPending ? (
                  <Loader2 className="h-4 w-4 animate-spin" />
                ) : (
                  <RefreshCw className="h-4 w-4" />
                )}
                {refresh.isPending ? "Refreshing…" : "Refresh Topics"}
              </button>
            ) : materials.data && materials.data.length > 0 ? (
              <button
                className="btn btn-primary"
                onClick={() => void generateTopics()}
                disabled={busy}
              >
                {generate.isPending ? (
                  <Loader2 className="h-4 w-4 animate-spin" />
                ) : (
                  <Sparkles className="h-4 w-4" />
                )}
                {generate.isPending ? "Generating…" : "Generate Topics"}
              </button>
            ) : null}
          </div>
        }
      />

      {actionError ? (
        <div className="mb-4 flex items-start gap-3 rounded-xl border border-destructive/30 bg-destructive/10 px-4 py-3">
          <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-destructive" />
          <div className="text-sm">
            <p className="text-destructive">{actionError.message}</p>
            {/* 400 means the course has no materials or nothing is indexed yet. */}
            {actionError instanceof ApiError && actionError.status === 400 ? (
              <Link
                to="/courses/$courseId/materials"
                params={{ courseId }}
                className="mt-1 inline-flex items-center gap-1 font-medium text-primary hover:underline"
              >
                <FolderOpen className="h-3.5 w-3.5" />
                Manage materials
              </Link>
            ) : null}
          </div>
        </div>
      ) : null}

      {topics.isLoading ? (
        <div className="card flex items-center justify-center gap-2 px-6 py-16 text-sm text-muted-foreground">
          <Loader2 className="h-4 w-4 animate-spin" />
          Loading topics…
        </div>
      ) : topics.isError ? (
        <div className="card px-6 py-16 text-center">
          <p className="font-medium">Couldn't load topics</p>
          <p className="mt-1 text-sm text-muted-foreground">
            {(topics.error as Error).message}
          </p>
          <button className="btn btn-primary mt-5" onClick={() => topics.refetch()}>
            Try again
          </button>
        </div>
      ) : list.length === 0 ? (
        materials.isLoading ? (
          <div className="card flex items-center justify-center gap-2 px-6 py-16 text-sm text-muted-foreground">
            <Loader2 className="h-4 w-4 animate-spin" />
            Loading topics…
          </div>
        ) : materials.data && materials.data.length === 0 ? (
          <EmptyState
            icon={FolderOpen}
            title="No materials yet"
            body="Upload slides, PDFs or lecture videos first — the knowledge map is generated from their content."
            action={
              <Link
                to="/courses/$courseId/materials"
                params={{ courseId }}
                className="btn btn-primary"
              >
                <FolderOpen className="h-4 w-4" />
                Add materials
              </Link>
            }
          />
        ) : (
          <EmptyState
            icon={Network}
            title="No topics yet"
            body="Generate the knowledge map from this course's materials. It is also refreshed automatically whenever a material finishes processing."
            action={
              <button
                className="btn btn-primary"
                onClick={() => void generateTopics()}
                disabled={busy}
              >
                {generate.isPending ? (
                  <Loader2 className="h-4 w-4 animate-spin" />
                ) : (
                  <Sparkles className="h-4 w-4" />
                )}
                {generate.isPending ? "Generating…" : "Generate Topics"}
              </button>
            }
          />
        )
      ) : (
        <div className="grid gap-3 lg:grid-cols-2">
          {list.map((topic) => (
            <TopicCard
              key={topic.id}
              topic={topic}
              selected={selected?.id === topic.id}
              materialNames={materialNames}
              onSelect={() => selectTopic(topic)}
            />
          ))}
        </div>
      )}
    </div>
  );
}

function TopicCard({
  topic,
  selected,
  materialNames,
  onSelect,
}: {
  topic: Topic;
  selected: boolean;
  materialNames: Map<string, string>;
  onSelect: () => void;
}) {
  const sources = topic.sourceMaterialIds
    .map((id) => materialNames.get(id))
    .filter((name): name is string => Boolean(name));

  return (
    <div className={cn("card p-5", selected && "border-primary/40")}>
      <button
        type="button"
        onClick={onSelect}
        aria-expanded={selected}
        className="flex w-full items-start justify-between gap-3 text-left"
      >
        <div className="min-w-0">
          <h3 className="truncate font-medium">{topic.name}</h3>
          {topic.description && (
            <p className="mt-1 text-sm text-muted-foreground">{topic.description}</p>
          )}
        </div>
        <ChevronDown
          className={cn(
            "mt-1 h-4 w-4 shrink-0 text-muted-foreground transition-transform",
            selected && "rotate-180",
          )}
        />
      </button>

      <div className="mt-3 flex flex-wrap items-center gap-2">
        {topic.generated && (
          <span className="chip text-primary">
            <Sparkles className="h-3 w-3" />
            AI
          </span>
        )}
        <span className="chip">
          <Layers className="h-3 w-3" />
          {topic.resources === 1 ? "1 material" : `${topic.resources} materials`}
        </span>
        {topic.group && <span className="chip">{topic.group}</span>}
        {topic.prerequisite && (
          <span className="chip">Needs {topic.prerequisite}</span>
        )}
      </div>

      {selected && (
        <div className="fade-up mt-4 space-y-4 border-t border-border pt-4">
          <div>
            <div className="text-xs font-medium uppercase tracking-wider text-muted-foreground">
              Source materials
            </div>
            {sources.length > 0 ? (
              <div className="mt-2 flex flex-wrap gap-2">
                {sources.slice(0, MAX_SOURCE_CHIPS).map((name) => (
                  <span key={name} className="chip">
                    <FileText className="h-3 w-3" />
                    {name}
                  </span>
                ))}
                {sources.length > MAX_SOURCE_CHIPS && (
                  <span className="chip">
                    +{sources.length - MAX_SOURCE_CHIPS} more
                  </span>
                )}
              </div>
            ) : (
              <p className="mt-1.5 text-sm text-muted-foreground">
                No source materials are recorded for this topic.
              </p>
            )}
          </div>
          <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-muted-foreground">
            <span>
              Appears in{" "}
              {topic.resources === 1 ? "1 material" : `${topic.resources} materials`}
            </span>
            <span>
              {topic.generated
                ? `Generated by ${topic.generationMethod ?? "the language model"}`
                : "Added by hand"}
            </span>
            {topic.updatedAt && (
              <span>
                Updated{" "}
                {new Date(topic.updatedAt).toLocaleDateString("en", {
                  month: "short",
                  day: "numeric",
                })}
              </span>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
